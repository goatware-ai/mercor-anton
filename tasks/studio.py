# Annotator-facing specs first; the rest are task-creation and reviewer audits.
SPEC_ORDER = ["Annotation Quality QC", "Annotation Quality QC (Reviewers)",
              "Annotation Quality QC (Annotator Advisory)"]


def rules(specs_path):
    specs = json.loads(Path(specs_path).read_text(encoding="utf-8"))
    specs = sorted((s for s in specs if s.get("is_latest")),
                   key=lambda s: (SPEC_ORDER.index(s["name"]) if s["name"] in SPEC_ORDER else 99, s["name"]))
    out = ["# AutoQC Rules", "",
           "> **Generated by `tasks/studio.py rules`** from the QC specs Studio loads on a task page. "
           "Don't edit by hand; re-run it on a fresh HAR when the specs change. This is the exact text "
           "the AutoQC agents grade against, so it outranks the docs when they disagree.", "",
           "| Spec | Version | Checks | Blocking | Purpose |", "|---|---|---|---|---|"]
    body = []
    for s in specs:
        rub = s["spec"].get("rubric") or {}
        dims = [(sec.get("name"), d) for sec in rub.get("sections", []) for d in sec.get("dimensions", [])]
        blocking = sum(d.get("importance") == "blocking" for _, d in dims)
        purpose = (s.get("description") or "").replace("|", "\\|").replace("\n", " ")
        out.append(f"| [{s['name']}](#{re.sub(r'[^a-z0-9 -]', '', s['name'].lower()).replace(' ', '-')}) "
                   f"| v{s['version']} | {len(dims)} | {blocking} | {purpose} |")
        body += ["", "---", "", f"## {s['name']}", "",
                 f"v{s['version']} · {s.get('status')} · subject: {s.get('subject_kind')}", "",
                 s.get("description") or "", "", rub.get("description") or ""]
        section = None
        for sec, d in dims:
            if sec != section:
                body += ["", f"### {sec}"]
                section = sec
            body += ["", f"#### {d.get('name')}", "",
                     f"`{d.get('dim_id')}` · **{d.get('importance') or 'non-blocking'}**", "",
                     d.get("description") or ""]
            for key, label in (("pass_criteria", "Pass"), ("fail_criteria", "Fail"),
                               ("neutral_criteria", "Neutral"), ("notes", "Notes")):
                if d.get(key):
                    body += ["", f"- **{label}:** {d[key]}"]
    dest = REPO / "docs" / "10-autoqc-rules.md"
    dest.write_text("\n".join(out + body) + "\n", encoding="utf-8")
    print(f"Wrote {dest.relative_to(REPO)}: {len(specs)} specs")


