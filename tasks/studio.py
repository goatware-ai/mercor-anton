results = []
COMPOUND = re.compile(r"\b(and|or)\b|,")


def note(level, ok, message):
    results.append((level, bool(ok), message))


def block(ok, message):
    results.append(("BLOCK", bool(ok), message))


def warn(ok, message):
    results.append(("WARN", bool(ok), message))


def as_score(v):
    return v if isinstance(v, int) and not isinstance(v, bool) and 1 <= v <= 5 else None


def check(path):
    task, src = load(path)
    cf = task["custom_fields"]

    # Studio's own form rules, when a capture saved them beside the export.
    schema_file = src.parent / "form-schema.json"
    schema = {f["field_id"]: f for f in json.loads(schema_file.read_text(encoding="utf-8"))} \
        if schema_file.is_file() else {}
    ours = ("2 · Trajectory", "3 · Adjudication")  # the groups an annotator fills in
    for fid, f in schema.items():
        value = cf.get(fid)
        if not (f.get("field_group") or "").startswith(ours):
            continue
        if f.get("required") and not f.get("display_hidden") and value in (None, ""):
            warn(False, f"{fid}: required by the Studio form and still empty ({f['label']})")
        if f.get("min_word_count") and isinstance(value, str) and value.strip():
            got = len(value.split())
            block(got >= f["min_word_count"],
                  f"{fid}: at least {f['min_word_count']} words (Studio 'Length limits') — got {got}")
        if f.get("options") and isinstance(value, str) and value and value not in f["options"] \
                and f["field_type"] != "likert_scale":
            warn(False, f"{fid}: value {value!r} is not one of {f['options']}")

    # Pair eligibility and Dimension 0
    gemini = cf.get("field_gemini_side")
    block(gemini in ("A", "B"), f"a Gemini trajectory is in the pair (gemini side: {gemini!r})")
    seeds = {s: cf.get(f"field_part1_{s}") for s in "ab"}
    block(all(v in STATUSES for v in seeds.values()), f"Dimension 0 set for both sides — got {seeds}")
    block(not all(v == "FAIL" for v in seeds.values()), "not both Dimension 0 FAIL (ineligible pair)")
    disposition = cf.get("field_part1_disposition")
    # Not an AutoQC gate since spec v10 ("upstream seed faults are left to the reviewer
    # audit"), but the Task Auditor checklist still rejects a both-FAIL pair.
    warn(disposition != "REJECT_BOTH_FAIL",
         f"Dimension 0 automated check does not say REJECT_BOTH_FAIL (got {disposition!r}) — "
         "if it does, verify the grading and ask before annotating an ineligible pair")
    for s in "ab":
        score = cf.get(f"field_score_{s}")
        warn(not (score == 0.0 and seeds[s] in ("PASS", "PARTIAL")),
             f"{s.upper()}: Dimension 0 {seeds[s]} agrees with the recorded score {score}")
        prov = cf.get(f"field_patch_{s}_provenance") or ""
        warn("reconstructed" not in prov,
             f"{s.upper()}: patch is a captured diff, not reconstructed from tool calls "
             "(reconstructed hunks and missing shell edits are harness artifacts, not agent behavior)")

    # Reason prose: LLM tells and the evidence rule (tasks/prose.py, docs/12)
    reasons = [(f"{s.upper()} dim {d}", cf.get(f"field_ta_dim{d}_reason_{s}"))
               for s in "ab" for d in DIMENSIONS]
    reasons += [(f"rubric {r['n']} {s.upper()}", r[f"reason_{s}"]) for r in rubrics(task) for s in "ab"]
    reasons.append(("comparative rationale", cf.get(F_RATIONALE)))
    for tag, text in reasons:
        for sev, cid, label, fix, _line, hit in prose.check_reason(text or ""):
            note(sev if cid != "em-dash" else "WARN", False,
                  f"{tag}: {label} — {hit!r}; {fix}" if cid != "no-evidence"
                  else f"{tag}: {label}; {fix}")

    # Dimensions 2-9 and final score
    final = {}
    for s in "ab":
        S = s.upper()
        for d, (score, reason) in dims(task, s).items():
            block(as_score(score) is not None,
                  f"{S} dim {d}: score is an integer 1-5 (a string like '3' shows as required in "
                  f"Studio's Navigation; re-select it) — got {score!r}")
            block(bool(reason and reason.strip()), f"{S} dim {d}: has a reason")
            if reason:
                warn(not OTHER_SIDE[s].search(reason),
                     f"{S} dim {d}: reason judges {S} on its own merits (no reference to the other side)")
        final[s] = as_score(cf.get(f"field_ta_final_quality_score_{s}"))
        block(final[s] is not None, f"{S}: final quality score is an integer 1-5 — "
                                    f"got {cf.get(f'field_ta_final_quality_score_{s}')!r}")
        scores = [as_score(v[0]) for v in dims(task, s).values()]
        if final[s] and all(scores):
            mean = sum(scores) / len(scores)
            warn(abs(final[s] - mean) <= 1, f"{S}: final score {final[s]} is within 1 of the "
                                            f"dimension mean {mean:.2f}")

    # Rubrics
    rs = rubrics(task)
    count = cf.get("field_rubric_count")
    block(RUBRIC_MIN <= len(rs) <= RUBRIC_MAX, f"{RUBRIC_MIN}-{RUBRIC_MAX} rubrics — got {len(rs)}")
    block(str(count) == str(len(rs)), f"Rubric count ({count!r}) matches the rubrics written ({len(rs)})")
    yes = {"a": 0, "b": 0}
    for r in rs:
        tag = f"rubric {r['n']}"
        block(bool(r["criteria"].strip()), f"{tag}: has criteria text")
        warn(not COMPOUND.search(r["criteria"]),
             f"{tag}: one independently gradable proposition (AutoQC aq_a1 fails a statement whose "
             f"parts could get different answers) — review: {r['criteria']!r}")
        for s in "ab":
            block(r[f"answer_{s}"] in ("YES", "NO"), f"{tag} {s.upper()}: answered YES/NO")
            block(bool((r[f"reason_{s}"] or "").strip()), f"{tag} {s.upper()}: has a reason")
            yes[s] += r[f"answer_{s}"] == "YES"
            if r[f"reason_{s}"]:
                warn(not OTHER_SIDE[s].search(r[f"reason_{s}"]),
                     f"{tag} {s.upper()}: reason cites this side's evidence, not the other side's")
        md = {s: str(r[f"mapped_dimension_{s}"] or "") for s in "ab"}
        block(all(v.isdigit() and int(v) in DIMENSIONS for v in md.values()),
              f"{tag}: mapped to one of dimensions 2-9 — got {md}")
        block(md["a"] == md["b"], f"{tag}: same mapped dimension on both sides")
    if rs:
        for s in "ab":
            rate = yes[s] / len(rs)
            who = ("Gemini side, AutoQC aq_a4" if s.upper() == gemini
                   else "non-Gemini side, reviewer comment")
            block(rate < PASS_RATE_LIMIT, f"{s.upper()} ({who}): rubric YES rate below 75% — "
                                          f"{yes[s]}/{len(rs)} = {rate:.0%}")
        warn(any(r["answer_a"] != r["answer_b"] for r in rs), "at least one rubric separates A from B")

    # Pairwise verdict
    pref = cf.get(F_PREFERENCE)
    block(pref in PREFERENCES, f"preference is one of {sorted(PREFERENCES)} — got {pref!r}")
    block(bool((cf.get(F_RATIONALE) or "").strip()), "comparative rationale is written")
    if pref in PREFERENCES and final["a"] and final["b"]:
        gap = final["a"] - final["b"]
        side = "A" if gap > 0 else "B"
        expected = "TIE" if gap == 0 else f"{side}_BETTER" if abs(gap) == 1 else f"{side}_MUCH_BETTER"
        block(pref == expected, f"preference is exactly the label the final-score gap maps to "
                                f"(AutoQC aq_c1: A {final['a']} − B {final['b']} = {gap} → {expected}) "
                                f"— got {pref}")

    if cf.get("field_adj_rationale"):
        warn(False, f"QC / reviewer note to address: {cf['field_adj_rationale']}")

    blocked = warns = 0
    for level, ok, message in results:
        blocked += level == "BLOCK" and not ok
        warns += level == "WARN" and not ok
        print(f"{'PASS' if ok else level:5}  {message}")
    print(f"\n{blocked} blocking, {warns} warnings — {'DO NOT SUBMIT' if blocked else 'ok to submit'}")
    print("Not checkable here: whether each reason is true, AutoQC's judgment checks "
          "(docs/10-autoqc-rules.md), and anything only the trajectories or the bundle show.")
    sys.exit(1 if blocked else 0)


