"""Fetch, unpack and check a Studio task.

    python3 tasks/studio.py har    <file.har>              # extension capture or DevTools HAR
    python3 tasks/studio.py unpack <task-export.json>      # -> tasks/<task-id>/studio/
    python3 tasks/studio.py check  <task-export.json | tasks/<task-id>>
    python3 tasks/studio.py rules  <tasks/<task-id>/studio/qc-specs.json>   # -> docs/10-autoqc-rules.md
    python3 tasks/studio.py form   <tasks/<task-id>/studio/form-schema.json> # -> docs/11-annotation-form.md

`har` reads a sanitized HAR recorded on the task page (docs/09-studio-flow.md
§2.1) and writes every piece of the task the page loaded: the task and rubrics
(then runs `unpack`), bundle files into harbor/, transcripts and logs into
trajectories/, reviewer comments, history, AutoQC audits and QC specs into
studio/. Signed download URLs are never written.

`unpack` copies the export into tasks/<task-id>/studio/export.json and writes
readable files beside it: meta.md, prompt.md, patch_a.diff, patch_b.diff,
final_answer_a.md, final_answer_b.md and annotation-current.md. Re-run it on
every fresh export; it overwrites studio/ and touches nothing else.

`check` applies the rules Studio's own "How this task works" page, Navigation
checklist and QC notes state (docs/09-studio-flow.md). BLOCK lines stop a
submission. WARN lines are judgment calls. Like gate.py, it cannot tell whether a
reason is true.

What an export does NOT contain: the trajectories (only S3 links), the task
bundle (environment/, solution/, tests/), AutoQC results and reviewer feedback.
docs/09-studio-flow.md §2 says how to fetch those.
"""

